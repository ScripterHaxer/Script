#!/usr/bin/env bash
# Stage: build the small boot initramfs (BusyBox + system/initramfs/init) that
# locates the boot medium and mounts the root image. Rootless: ownership and
# device nodes are declared in the gen_init_cpio list.
source "$(dirname "$0")/../lib/common.sh"

list="$BUILD_DIR/initramfs.list"
out="$OUT_DIR/initramfs.img"
gen_cpio="$BUILD_DIR/kernel-obj/usr/gen_init_cpio"
[[ -x "$gen_cpio" ]] || die "gen_init_cpio not found; build the kernel stage first"
[[ -f "$OUT_DIR/rootfs.squashfs.sha256" ]] || die "root image missing; run the rootfs stage first"

{
    echo "# Generated by tools/build/initramfs.sh — do not edit."
    for d in /bin /dev /etc /proc /sys /run /newroot; do echo "dir $d 0755 0 0"; done
    echo "nod /dev/console 0600 0 0 c 5 1"
    echo "nod /dev/null 0666 0 0 c 1 3"
    echo "file /bin/busybox $OUT_DIR/busybox 0755 0 0"
    echo "slink /bin/sh busybox 0777 0 0"   # interpreter for /init itself
    echo "file /init $GIDEON_ROOT/system/initramfs/init 0755 0 0"
    # The root image this initramfs accepts (see init: find_media).
    echo "file /etc/gideon-rootfs.sha256 $OUT_DIR/rootfs.squashfs.sha256 0644 0 0"
} > "$list"

"$gen_cpio" -t "$SOURCE_DATE_EPOCH" "$list" | gzip -n -9 > "$out.tmp"
mv "$out.tmp" "$out"
ok "initramfs: $(du -h "$out" | cut -f1) -> build/out/initramfs.img"
