#!/usr/bin/env bash
# Stage: assemble the root filesystem and pack it as a gzip'd cpio initramfs.
# Needs no root privileges: ownership and device nodes are declared in the
# cpio list consumed by the kernel's gen_init_cpio, not created on the host.
source "$(dirname "$0")/../lib/common.sh"

root="$BUILD_DIR/rootfs"
list="$BUILD_DIR/initramfs.list"
out="$OUT_DIR/initramfs.img"
gen_cpio="$BUILD_DIR/kernel-obj/usr/gen_init_cpio"
[[ -x "$gen_cpio" ]] || die "gen_init_cpio not found; build the kernel stage first"
[[ -x "$OUT_DIR/busybox" ]] || die "busybox not built; run the busybox stage first"

log "Assembling root filesystem"
rm -rf "$root"; mkdir -p "$root"

# Filesystem hierarchy (FHS). /usr/lib/gideon and /etc/gideon hold the
# GideonOS system scripts and configuration respectively.
for d in bin sbin boot dev etc home lib media mnt opt proc root run srv sys tmp \
         usr/bin usr/sbin usr/lib usr/share usr/local/bin usr/local/sbin \
         var/cache var/lib var/log var/tmp var/spool etc/profile.d; do
    mkdir -p "$root/$d"
done
ln -s ../run "$root/var/run"

cp -a "$GIDEON_ROOT/system/rootfs/." "$root/"
find "$root" -name .keep -delete

build_id="$(git -C "$GIDEON_ROOT" rev-parse --short=12 HEAD 2>/dev/null || echo unknown)"
sed -e "s/@GIDEON_VERSION@/$GIDEON_VERSION/g" \
    -e "s/@GIDEON_CODENAME@/$GIDEON_CODENAME/g" \
    -e "s/@GIDEON_CODENAME_LC@/${GIDEON_CODENAME,,}/g" \
    -e "s/@BUILD_ID@/$build_id/g" \
    "$root/etc/os-release.in" > "$root/etc/os-release"
rm "$root/etc/os-release.in"
ln -s ../etc/os-release "$root/usr/lib/os-release"

# BusyBox and its applet links (relative, so the tree is relocatable).
install -m 0755 "$OUT_DIR/busybox" "$root/bin/busybox"
while IFS= read -r applet; do
    [[ "$applet" == bin/busybox || -e "$root/$applet" ]] && continue
    up="$(dirname "$applet" | sed -E 's#[^/]+#..#g')"
    ln -s "$up/bin/busybox" "$root/$applet"
done < "$OUT_DIR/busybox.links"
ln -s sbin/init "$root/init"

chmod 0755 "$root"; chmod 0700 "$root/root"; chmod 1777 "$root/tmp" "$root/var/tmp"
chmod 0600 "$root/etc/shadow"

log "Writing initramfs file list"
{
    echo "# Generated by tools/build/rootfs.sh — do not edit."
    echo "dir /dev 0755 0 0"
    echo "nod /dev/console 0600 0 0 c 5 1"
    echo "nod /dev/null 0666 0 0 c 1 3"
    (cd "$root" && find . -mindepth 1 | LC_ALL=C sort) | while IFS= read -r p; do
        p="${p#.}"; f="$root$p"; mode="$(stat -c %a "$f")"
        [[ "$p" == /dev ]] && continue
        if [[ -L "$f" ]]; then echo "slink $p $(readlink "$f") 0777 0 0"
        elif [[ -d "$f" ]]; then echo "dir $p $mode 0 0"
        elif [[ -f "$f" ]]; then echo "file $p $f $mode 0 0"
        else die "unsupported file type in rootfs: $p"; fi
    done
} > "$list"

"$gen_cpio" -t "$SOURCE_DATE_EPOCH" "$list" | gzip -n -9 > "$out.tmp"
mv "$out.tmp" "$out"
ok "initramfs: $(du -h "$out" | cut -f1) ($(grep -vc '^#' "$list") entries) -> build/out/initramfs.img"
